#!/usr/bin/env node
/**
 * 构建前写入公开部署快照：
 * - public/deploy-env.json
 * - public/site-version.json
 * - functions/_worker-b-config.js（Pages Functions 公开读代理回落）
 *
 * M9-AUDIT-3：CF Pages / 严格部署模式下缺 PUBLIC_WORKER_B_URL 必须失败，
 * 禁止把本地空配置当成生产构建产物。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.join(__dirname, '..');
const outPath = path.join(webRoot, 'public', 'deploy-env.json');
const versionConfigPath = path.join(webRoot, 'version.config.json');
const versionOutPath = path.join(webRoot, 'public', 'site-version.json');
const functionsConfigPath = path.join(webRoot, 'functions', '_worker-b-config.js');

export function trimUrl(v) {
  if (typeof v !== 'string') return '';
  return v.trim().replace(/\/+$/, '');
}

/**
 * 严格部署构建：Cloudflare Pages、显式 HAILUO_DEPLOY_STRICT、或要求 URL 的 CI。
 * 本地 `npm run build` 默认非严格，可写空配置并告警。
 */
export function isStrictDeployBuild(env = process.env) {
  const flag = (key) => String(env[key] ?? '').trim().toLowerCase();
  if (flag('HAILUO_ALLOW_EMPTY_WORKER_B_CONFIG') === '1' || flag('HAILUO_ALLOW_EMPTY_WORKER_B_CONFIG') === 'true') {
    return false;
  }
  return flag('CF_PAGES') === '1'
    || flag('HAILUO_DEPLOY_STRICT') === '1'
    || flag('HAILUO_DEPLOY_STRICT') === 'true'
    || flag('HAILUO_REQUIRE_PUBLIC_WORKER_B_URL') === '1'
    || flag('HAILUO_REQUIRE_PUBLIC_WORKER_B_URL') === 'true';
}

export function buildDeployPayload(env = process.env) {
  return {
    worker_b_url: trimUrl(env.PUBLIC_WORKER_B_URL),
    registry_url: trimUrl(env.PUBLIC_REGISTRY_URL),
  };
}

/** 严格模式下缺 Worker B URL → 抛错（中文）。 */
export function assertDeployPayloadOrThrow(payload, strict) {
  if (!strict) return;
  if (!payload.worker_b_url) {
    throw new Error(
      '[write-deploy-env] 严格部署构建缺少 PUBLIC_WORKER_B_URL。'
      + '请在 Cloudflare Pages Production 构建变量中设置 Worker B 公开 https 地址；'
      + '并确认 Pages 已绑定 STATE_KV（与 Worker A/B 同 namespace）。'
      + '本地调试若必须空配置，可设 HAILUO_ALLOW_EMPTY_WORKER_B_CONFIG=1。',
    );
  }
}

function pad2(n) {
  return String(n).padStart(2, '0');
}

function readVersionPrefix() {
  const raw = fs.readFileSync(versionConfigPath, 'utf8');
  const parsed = JSON.parse(raw);
  const prefix = typeof parsed.prefix === 'string' ? parsed.prefix.trim() : '';
  if (!/^\d+(?:\.\d+)*$/.test(prefix)) {
    throw new Error('version.config.json prefix must look like "1.1"');
  }
  return prefix;
}

export function buildSiteVersion() {
  const now = new Date();
  const stamp = [
    pad2(now.getFullYear() % 100),
    pad2(now.getMonth() + 1),
    pad2(now.getDate()),
    pad2(now.getHours()),
  ].join('');
  const randomCode = pad2(Math.floor(Math.random() * 100));
  return `${readVersionPrefix()}.${stamp}.${randomCode}`;
}

export function writeDeployArtifacts(payload, siteVersion, {
  deployEnvPath = outPath,
  versionPath = versionOutPath,
  functionsConfig = functionsConfigPath,
} = {}) {
  fs.mkdirSync(path.dirname(deployEnvPath), { recursive: true });
  fs.mkdirSync(path.dirname(versionPath), { recursive: true });
  fs.mkdirSync(path.dirname(functionsConfig), { recursive: true });
  fs.writeFileSync(deployEnvPath, `${JSON.stringify(payload)}\n`, 'utf8');
  fs.writeFileSync(versionPath, `${JSON.stringify({ version: siteVersion })}\n`, 'utf8');
  // 生成文件头注释：提醒勿手改、勿把空本地产物当生产源码提交
  const body = `/** Generated by write-deploy-env.mjs — do not hand-edit; not a source SSOT. */\n`
    + `export default ${JSON.stringify(payload, null, 2)};\n`;
  fs.writeFileSync(functionsConfig, body, 'utf8');
}

export function main(env = process.env) {
  const repoRoot = path.join(__dirname, '..', '..');
  const genAllowlist = spawnSync(process.execPath, ['scripts/gen-owner-gateway-allowlist.mjs'], {
    cwd: repoRoot,
    stdio: 'inherit',
    env,
  });
  if (genAllowlist.status !== 0) {
    throw new Error('gen-owner-gateway-allowlist.mjs failed');
  }

  const strict = isStrictDeployBuild(env);
  const payload = buildDeployPayload(env);
  assertDeployPayloadOrThrow(payload, strict);

  if (!payload.worker_b_url) {
    console.warn(
      '[write-deploy-env] 警告：PUBLIC_WORKER_B_URL 为空；'
      + '本地可继续，但公开读依赖 STATE_KV 或后续注入。'
      + '生产 Pages 构建须设置该变量（CF_PAGES=1 时本脚本会直接失败）。',
    );
  }

  const siteVersion = buildSiteVersion();
  writeDeployArtifacts(payload, siteVersion);
  console.log('[write-deploy-env] public/deploy-env.json');
  console.log(`[write-deploy-env] public/site-version.json version=${siteVersion}`);
  console.log('[write-deploy-env] functions/_worker-b-config.js');
  console.log(`[write-deploy-env] strict=${strict ? 'yes' : 'no'} worker_b_url=${payload.worker_b_url || '(empty)'}`);
}

const isDirectRun = process.argv[1]
  && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirectRun) {
  try {
    main();
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
